function cleanForYemotTTS(raw) {
  return (raw || "")
    .replace(/[\r\n.]/g, " ")
    .replace(/[^א-ת0-9,\s]/g, " ")
    .replace(/\s*,\s*/g, ", ")
    .replace(/\s+/g, " ")
    .trim();
}

